/**
 * Regenerates src/artifacts.ts (ABI + creation bytecode of the Fengce contracts) from the
 * forge build output, so the published package does not need the Foundry project.
 *   (cd .. && forge build) && npx tsx scripts/sync-artifacts.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../../out");
const names = ["PinRegistry", "FengceGuard", "FengceSignatureVerifier", "FengceStrictHandler", "Catalog", "Tick", "UniswapV3RouterDecoder", "UniswapV2RouterDecoder", "AaveV3PoolDecoder"];
let ts = "// Generated by scripts/sync-artifacts.ts from the forge build output. Do not edit by hand.\n\n";
for (const n of names) {
  const j = JSON.parse(readFileSync(resolve(out, `${n}.sol`, `${n}.json`), "utf8"));
  ts += `export const ${n}Artifact = {\n  abi: ${JSON.stringify(j.abi)} as const,\n  bytecode: "${j.bytecode.object}" as \`0x\${string}\`,\n};\n\n`;
}
writeFileSync(resolve(here, "../src/artifacts.ts"), ts);
console.log(`wrote src/artifacts.ts (${names.join(", ")})`);
